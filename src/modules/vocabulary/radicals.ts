/** "149'" → { number: 149, char: '讠', nameVi: 'ngôn' }; "39" → 子 tử. */
export function radicalOf(
  code: string,
): { number: number; char: string; nameVi: string } | null {
  const number = parseInt(code, 10);
  const r = RADICALS[number - 1];
  if (!r) return null;
  const simplified = code.endsWith("'");
  return { number, char: simplified && r[2] ? r[2] : r[0], nameVi: r[1] };
}
